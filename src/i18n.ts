export function language(): string {
  try {
    return getLanguage();
  } catch {
    return "en";
  }
}

/** The string for `key` in Obsidian's language; `{name}` placeholders are replaced from `vars`. */
export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
  const s = (language().startsWith("fr") ? fr[key] : undefined) ?? en[key];
  return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
